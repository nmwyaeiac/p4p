    private void BAjoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BAjoutActionPerformed
        // TODO add your handling code here:
        // récupération de l'indice sélectionné
        int ind = this.LJoueursDispo.getSelectedIndex();
        if(ind != 1){ // on vérifie qu'un élément est sélectionné
            // on vérifie qu'il n'y a pas déja 2 joueurs sélectionnés
            if(LJoueurs.getModel().getSize()<2){ // récupération du pseudo sélectionné
                String ps = LJoueursDispo.getSelectedValue();
                DefaultListModel mod1 = (DefaultListModel) LJoueursDispo.getModel();
                DefaultListModel mod2 = (DefaultListModel) LJoueurs.getModel();
                mod1.remove(ind);
                mod2.addElement(ps);
            }
        }
    }//GEN-LAST:event_BAjoutActionPerformed

    private void BRetraitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRetraitActionPerformed
        // TODO add your handling code here:
        int ind = this.LJoueurs.getSelectedIndex();
        if(ind != -1){ // il y a une selection
            String ps = LJoueurs.getSelectedValue();
            DefaultListModel mod1 = (DefaultListModel)this.LJoueursDispo.getModel();
            DefaultListModel mod2 = (DefaultListModel)this.LJoueurs.getModel();
            // on déplace le nom du pseudo
            mod1.addElement(ps);
            mod2.remove(ind); // supprime lélément à cet indice
        }
    }//GEN-LAST:event_BRetraitActionPerformed

    private void BValiderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BValiderActionPerformed
        // TODO add your handling code here:
        // on vérifie qu'il y a 2 joueurs dans la liste LJoueurs(JList)
        if(LJoueurs.getModel().getSize()==2){
            String ps1 = LJoueurs.getModel().getElementAt(0); // 1ere élément
            String ps2 = LJoueurs.getModel().getElementAt(1); // 2eme élément
            this.joueur1 = this.lj.rechJoueur(ps1);
            this.joueur2 = this.lj.rechJoueur(ps2);
            this.ok = true;
            // fermeture de la boîte
            this.setVisible(false);
            this.dispose();
        }
        else{
            LMessage.setText("Il faut 2 joueurs!");
        }
    }//GEN-LAST:event_BValiderActionPerformed

