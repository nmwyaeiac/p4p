    private void initListesJoueurs(){
        // rempli la JList avec les pseudos des joueurs
        // usage d'un modèle
        DefaultListModel mod = new DefaultListModel();
        LJoueursDispo.setModel(mod);
        for(int i=0; i<this.lj.getNbJoueurs(); i++){
            mod.addElement(this.lj.getJoueur(i).getPseudo());
            DefaultListModel mod2 = new DefaultListModel();
            LJoueurs.setModel(mod2);
        }
    }
    
